</p>
<p>
	 Сейчас офтальмология развивается семимильными шагами. Ее динамическое развитие обусловило появление инновационных решений в оснащении кабинета для офтальмолога. Ведь именно с функциональной диагностики заболеваний начинается путь пациента к терапии или хирургии, а в дальнейшем реабилитация подкрепляется физиотерапией.
